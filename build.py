#!/usr/bin/env python3
"""Build blog.atomai.click from posts/*.md into static HTML at the repo root.

Usage: python3 build.py
Each post is posts/<slug>.md with a front matter block (title, date, description, tags) followed by
Markdown that may contain inline HTML. Output: <slug>/index.html, index.html, tags/index.html,
feed.xml, sitemap.xml. Everything written here is generated output: edit posts/ and rerun.
"""
import html
import re
import shutil
import sys
from datetime import datetime, timezone
from email.utils import format_datetime
from pathlib import Path

import markdown

SITE_URL = "https://blog.atomai.click"
SITE_TITLE = "Atom 기술 블로그"
SITE_DESC = "AWS와 Kubernetes를 직접 구성하고 확인한 기록"
GA_ID = "G-GWVLEW5JLL"
ROOT = Path(__file__).resolve().parent
POSTS = ROOT / "posts"
MARKER = "generated by build.py"

PAGE = """<!DOCTYPE html>
<html lang="ko">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <!-- {marker} from {src}; do not edit -->
  <title>{title}</title>
  <meta name="description" content="{description}">
  <link rel="canonical" href="{url}">
  <meta property="og:type" content="{og_type}">
  <meta property="og:title" content="{title}">
  <meta property="og:description" content="{description}">
  <meta property="og:url" content="{url}">
  <meta property="og:site_name" content="{site_title}">
  <link rel="alternate" type="application/rss+xml" title="{site_title}" href="/feed.xml">
  <link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="/assets/style.css">
  <script async src="https://www.googletagmanager.com/gtag/js?id={ga}"></script>
  <script>window.dataLayer=window.dataLayer||[];function gtag(){{dataLayer.push(arguments)}}gtag('js',new Date());gtag('config','{ga}');</script>
</head>
<body>
<header class="site-header"><div class="inner">
  <a class="brand" href="/">{site_title}</a>
  <nav class="site-nav"><a href="/">글 목록</a><a href="/tags/">태그</a><a href="/feed.xml">RSS</a></nav>
</div></header>
<main class="wrap">
{main}
</main>
<footer class="site-footer"><div class="inner">blog.atomai.click. 발표 자료는 <a href="https://presentation.atomai.click/">presentation.atomai.click</a>에 있습니다.</div></footer>
{scripts}
</body>
</html>
"""

# Only one video plays at a time (posts that embed demo recordings).
VIDEO_JS = """<script>
document.querySelectorAll('video').forEach(function (v) {
  v.addEventListener('play', function () {
    document.querySelectorAll('video').forEach(function (o) { if (o !== v && !o.paused) o.pause(); });
  });
});
</script>"""


def parse(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        sys.exit(f"{path.name}: missing front matter")
    meta = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        if k.strip():
            meta[k.strip()] = v.strip().strip('"')
    for key in ("title", "date", "description"):
        if not meta.get(key):
            sys.exit(f"{path.name}: front matter needs '{key}'")
    try:
        date = datetime.strptime(meta["date"], "%Y-%m-%d").replace(tzinfo=timezone.utc)
    except ValueError:
        sys.exit(f"{path.name}: date must be YYYY-MM-DD, got {meta['date']!r}")
    body_md = text[m.end():]
    # The page header renders the title, so drop a leading "# title" line from the body.
    body_md = re.sub(r"^\s*# [^\n]*\n", "", body_md, count=1)
    # md_in_html parses Markdown inside blocks marked markdown="1" (the table of contents).
    body = markdown.markdown(body_md, extensions=["tables", "fenced_code", "md_in_html"], output_format="html5")
    tags = [t.strip() for t in meta.get("tags", "").split(",") if t.strip()]
    return {"slug": path.stem, "src": f"posts/{path.name}", "title": meta["title"], "date": date,
            "description": meta["description"], "tags": tags, "body": body,
            "url": f"{SITE_URL}/{path.stem}/", "videos": "<video" in body}


def esc(s: str) -> str:
    return html.escape(s, quote=True)


def tag_links(tags: list) -> str:
    if not tags:
        return ""
    items = "".join(f'<li><a href="/tags/#{esc(t)}">#{esc(t)}</a></li>' for t in tags)
    return f'<ul class="tags">{items}</ul>'


def page(*, src, title, description, url, main, og_type="website", scripts=""):
    return PAGE.format(marker=MARKER, src=src, title=esc(title), description=esc(description), url=url,
                       og_type=og_type, site_title=esc(SITE_TITLE), ga=GA_ID, main=main, scripts=scripts)


def item(p: dict, heading="h2") -> str:
    return (f'<li class="post-item"><span class="meta">{p["date"]:%Y-%m-%d}</span>'
            f'<{heading}><a href="/{p["slug"]}/">{esc(p["title"])}</a></{heading}>'
            f'<p>{esc(p["description"])}</p>{tag_links(p["tags"])}</li>')


def write(rel: str, content: str) -> None:
    out = ROOT / rel
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(content, encoding="utf-8")
    print(f"wrote {rel}")


def clean_stale(slugs: set) -> None:
    """Remove generated post directories whose source post no longer exists."""
    for d in ROOT.iterdir():
        idx = d / "index.html"
        if d.is_dir() and d.name not in slugs and d.name != "tags" and idx.exists() \
                and MARKER in idx.read_text(encoding="utf-8")[:600]:
            shutil.rmtree(d)
            print(f"removed stale {d.name}/")


def main() -> None:
    posts = sorted((parse(p) for p in POSTS.glob("*.md")), key=lambda p: (p["date"], p["slug"]), reverse=True)
    if not posts:
        sys.exit("no posts in posts/")
    clean_stale({p["slug"] for p in posts})

    for i, p in enumerate(posts):
        newer = posts[i - 1] if i > 0 else None
        older = posts[i + 1] if i + 1 < len(posts) else None
        nav = '<nav class="post-nav">'
        nav += f'<a href="/{older["slug"]}/">이전 글: {esc(older["title"])}</a>' if older else "<span></span>"
        nav += f'<a href="/{newer["slug"]}/">다음 글: {esc(newer["title"])}</a>' if newer else "<span></span>"
        nav += "</nav>"
        main_html = (f'<article>\n<header class="post-head"><h1>{esc(p["title"])}</h1>'
                     f'<div class="meta"><time datetime="{p["date"]:%Y-%m-%d}">{p["date"]:%Y-%m-%d}</time>'
                     f'{tag_links(p["tags"])}</div></header>\n{p["body"]}\n{nav}\n</article>')
        write(f'{p["slug"]}/index.html', page(src=p["src"], title=p["title"], description=p["description"],
                                              url=p["url"], main=main_html, og_type="article",
                                              scripts=VIDEO_JS if p["videos"] else ""))

    home = (f'<p class="intro">{esc(SITE_DESC)}</p>\n<ul class="post-list">'
            + "".join(item(p) for p in posts) + "</ul>")
    write("index.html", page(src="posts/", title=SITE_TITLE, description=SITE_DESC, url=f"{SITE_URL}/", main=home))

    by_tag = {}
    for p in posts:
        for t in p["tags"]:
            by_tag.setdefault(t, []).append(p)
    groups = "".join(f'<section class="tag-group" id="{esc(t)}"><h2>#{esc(t)} ({len(ps)})</h2>'
                     f'<ul class="post-list">{"".join(item(x, "h3") for x in ps)}</ul></section>'
                     for t, ps in sorted(by_tag.items()))
    write("tags/index.html", page(src="posts/", title=f"태그 | {SITE_TITLE}", description="태그별 글 목록",
                                  url=f"{SITE_URL}/tags/", main=f"<h1>태그</h1>\n{groups}"))

    rss_items = "".join(
        f"<item><title>{esc(p['title'])}</title><link>{p['url']}</link><guid>{p['url']}</guid>"
        f"<pubDate>{format_datetime(p['date'])}</pubDate><description>{esc(p['description'])}</description>"
        + "".join(f"<category>{esc(t)}</category>" for t in p["tags"]) + "</item>"
        for p in posts)
    write("feed.xml", f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- {MARKER}; do not edit -->\n'
                      f'<rss version="2.0"><channel><title>{esc(SITE_TITLE)}</title><link>{SITE_URL}/</link>'
                      f'<description>{esc(SITE_DESC)}</description><language>ko</language>'
                      f'<lastBuildDate>{format_datetime(posts[0]["date"])}</lastBuildDate>{rss_items}</channel></rss>\n')

    urls = [(f"{SITE_URL}/", posts[0]["date"]), (f"{SITE_URL}/tags/", posts[0]["date"])]
    urls += [(p["url"], p["date"]) for p in posts]
    write("sitemap.xml", f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- {MARKER}; do not edit -->\n'
                         '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
                         + "".join(f"<url><loc>{u}</loc><lastmod>{d:%Y-%m-%d}</lastmod></url>" for u, d in urls)
                         + "</urlset>\n")


if __name__ == "__main__":
    main()
